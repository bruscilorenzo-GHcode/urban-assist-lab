export type Strings = typeof STRINGS.it
export const STR: Record<UiLang, Strings> = STRINGS as unknown as Record<UiLang, Strings>

const STORAGE_KEY = 'assist-urban.ui-lang'

export function loadUiLang(storage?: Pick<Storage, 'getItem'> | null): UiLang {
  try {
    const saved = storage?.getItem(STORAGE_KEY)
    return saved === 'en' || saved === 'it' ? saved : 'it'
  } catch {
    return 'it'
  }
}

export function storeUiLang(lang: UiLang, storage?: Pick<Storage, 'setItem'> | null): void {
  try {
    storage?.setItem(STORAGE_KEY, lang)
  } catch {
    // ignore
  }
  if (typeof document !== 'undefined') document.documentElement.lang = lang
}
